/**
 * Title sanitisation for imported sessions.
 *
 * Agents inject boilerplate system messages that are not real titles, most
 * visibly Claude's "This session is being continued from a previous
 * conversation that ran out of context …" compaction notice, which otherwise
 * becomes the session title in the sidebar and breadcrumb. These helpers detect
 * that boilerplate so the importer can fall back to a meaningful title (the
 * first real turn, or the project name) instead.
 */

const AGENT_BOILERPLATE_TITLE_PREFIXES = [
  "this session is being continued from a previous conversation",
  "caveat: the messages below were generated by the user while running",
  "<system-reminder>",
  "<command-name>",
  // Harness-injected background-task events and system notices arrive as
  // user-role messages but are machine noise, never a real ask. Without this
  // they open spurious request columns / become session titles.
  "<task-notification>",
  "[system notification",
  // A cancel, not a request: the agent writes this when the user interrupts.
  "[request interrupted",
];

/**
 * Whether a title is an agent-injected boilerplate notice rather than real
 * work. Case-insensitive prefix match on the known injections.
 */
export function isAgentBoilerplateTitle(title: string): boolean {
  const normalized = title.trim().toLowerCase();
  if (!normalized) return false;
  return AGENT_BOILERPLATE_TITLE_PREFIXES.some((prefix) => normalized.startsWith(prefix));
}

/**
 * Return the title when it reads as a real one, else "". The caller supplies
 * the fallback (e.g. the first non-boilerplate turn, then the project name), so
 * this stays a pure predicate-trim with no opinion about what replaces it.
 */
export function cleanImportedTitle(title: string | undefined | null): string {
  const trimmed = (title ?? "").trim();
  if (!trimmed || isAgentBoilerplateTitle(trimmed)) return "";
  return trimmed;
}

/**
 * Pick the best title from a candidate's own turn titles: the first one that is
 * neither empty nor boilerplate. Returns "" when every title is boilerplate.
 */
export function firstMeaningfulTitle(titles: readonly string[]): string {
  for (const title of titles) {
    const cleaned = cleanImportedTitle(title);
    if (cleaned) return cleaned;
  }
  return "";
}
