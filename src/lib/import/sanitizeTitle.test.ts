import { describe, expect, it } from "vitest";

import {
  cleanImportedTitle,
  firstMeaningfulTitle,
  isAgentBoilerplateTitle,
} from "./sanitizeTitle";

describe("sanitizeTitle", () => {
  it("detects the Claude continuation boilerplate as not a real title", () => {
    expect(
      isAgentBoilerplateTitle(
        "This session is being continued from a previous conversation that ran out of context. The...",
      ),
    ).toBe(true);
    expect(isAgentBoilerplateTitle("Caveat: The messages below were generated by the user while running local commands.")).toBe(true);
    expect(isAgentBoilerplateTitle("Wire the gateway routing table")).toBe(false);
  });

  it("detects harness-injected system messages as not real titles", () => {
    expect(isAgentBoilerplateTitle("<task-notification>\n<task-id>abc</task-id>")).toBe(true);
    expect(isAgentBoilerplateTitle("[SYSTEM NOTIFICATION - NOT USER INPUT]")).toBe(true);
    expect(isAgentBoilerplateTitle("<command-name>/model</command-name>")).toBe(true);
    expect(isAgentBoilerplateTitle("<system-reminder>do the thing</system-reminder>")).toBe(true);
  });

  it("detects slash-command wrappers and resume prompts as not real requests", () => {
    expect(
      isAgentBoilerplateTitle("<local-command-caveat>Caveat: The messages below were generated"),
    ).toBe(true);
    expect(isAgentBoilerplateTitle("<local-command-stdout>Set model to claude-fable-5")).toBe(true);
    expect(isAgentBoilerplateTitle("Continue from where you left off.")).toBe(true);
    // A genuine ask that merely mentions continuing is still a real title.
    expect(isAgentBoilerplateTitle("계속 진행해줘")).toBe(false);
  });

  it("cleanImportedTitle drops boilerplate and keeps real titles", () => {
    expect(cleanImportedTitle("This session is being continued from a previous conversation")).toBe("");
    expect(cleanImportedTitle("  ")).toBe("");
    expect(cleanImportedTitle("Refactor the auth middleware")).toBe("Refactor the auth middleware");
  });

  it("firstMeaningfulTitle skips boilerplate turns to the first real one", () => {
    expect(
      firstMeaningfulTitle([
        "This session is being continued from a previous conversation that ran out of context.",
        "도구 결과",
        "벡터 임베딩 마이그레이션을 확인해줘",
      ]),
    ).toBe("도구 결과");
    expect(firstMeaningfulTitle(["This session is being continued from a previous conversation"])).toBe("");
  });
});

import { boilerplateLabel } from "./sanitizeTitle";

describe("what an injected notice is", () => {
  it("names a slash command, its output, a caveat, a continuation and a cancel", () => {
    expect(boilerplateLabel("<command-name>/model</command-name> <command-message>model</command-message>")).toBe("/model 명령");
    expect(boilerplateLabel("<local-command-stdout>Set model</local-command-stdout>")).toBe("명령 출력");
    expect(boilerplateLabel("<local-command-caveat>Caveat: The messages below were generated</local-command-caveat>")).toBe("로컬 명령 안내");
    expect(boilerplateLabel("This session is being continued from a previous conversation that ran out of context.")).toBe("세션 이어가기");
    expect(boilerplateLabel("[Request interrupted by user]")).toBe("요청 중단");
  });

  it("is empty for a real request", () => {
    expect(boilerplateLabel("CI 개선 계획을 세워줘")).toBe("");
  });
});
