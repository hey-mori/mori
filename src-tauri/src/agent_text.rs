//! Telling a person's request apart from text an agent harness injected into
//! the user role.
//!
//! Claude Code and Codex both put machine text in user-role messages: slash
//! command records (`<command-name>`, `<local-command-stdout>`), notices
//! (`<local-command-caveat>`, `<system-reminder>`), and context preambles
//! (`<environment_context>`, `<recommended_plugins>`). Across the NUC's real logs
//! (2026-10-08) every one of them begins with an XML-style tag, and no real
//! prompt does. So the rule is structural, not a list of strings that drifts
//! with each CLI release: user text that OPENS with `<identifier>` is an
//! envelope, never a title. A prompt that merely contains a tag later on, or
//! starts with something like `<3`, is not affected.

/// Whether `text` opens with a harness tag such as `<command-name>` or
/// `<environment_context>`: `<`, a lowercase identifier (letters, digits, `-`,
/// `_`), then `>`.
pub fn is_harness_envelope(text: &str) -> bool {
    let trimmed = text.trim_start();
    let Some(rest) = trimmed.strip_prefix('<') else {
        return false;
    };
    let Some(end) = rest.find('>') else {
        return false;
    };
    let name = &rest[..end];
    let mut chars = name.chars();
    matches!(chars.next(), Some(first) if first.is_ascii_lowercase())
        && chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-' || c == '_')
}

/// The slash command a Claude Code command record names
/// (`<command-name>/model</command-name>` gives `/model`), if any.
pub fn slash_command_name(text: &str) -> Option<String> {
    let start = text.find("<command-name>")? + "<command-name>".len();
    let end = text[start..].find("</command-name>")? + start;
    let name = text[start..end].trim();
    if name.is_empty() {
        None
    } else {
        Some(name.to_string())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn harness_envelopes_seen_in_real_logs_are_recognised() {
        for text in [
            "<local-command-caveat>Caveat: The messages below were generated by the user</local-command-caveat>",
            "<command-name>/model</command-name>\n<command-message>model</command-message>",
            "<local-command-stdout>Set model to opus</local-command-stdout>",
            "<system-reminder>Plan mode is active.</system-reminder>",
            "<environment_context>\n  <cwd>/home/u/dev/window</cwd>\n</environment_context>",
            "<recommended_plugins> Here is a list of plugins",
            "  <command-name>/clear</command-name>",
        ] {
            assert!(is_harness_envelope(text), "should be an envelope: {text}");
        }
    }

    #[test]
    fn a_real_request_is_never_mistaken_for_an_envelope() {
        for text in [
            "Mori 개발 재개 상태를 점검해 줘",
            "Fix the <div> that overflows on mobile",
            "<3 thanks, now add the test",
            "<Button> renders twice, why?",
            "< not a tag",
            "",
        ] {
            assert!(!is_harness_envelope(text), "should be a request: {text}");
        }
    }

    #[test]
    fn reads_the_slash_command_out_of_a_command_record() {
        assert_eq!(
            slash_command_name("<command-name>/model</command-name>\n<command-args>opus</command-args>"),
            Some("/model".to_string())
        );
        assert_eq!(slash_command_name("plain text"), None);
        assert_eq!(slash_command_name("<command-name>  </command-name>"), None);
    }
}
